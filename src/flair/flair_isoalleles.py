def get_bedisoform_info(bedisofile):
    isoforms = {}
    gene_to_isoforms, gene_to_all_exons = {}, {}
    gene_to_chrom = {}
    for bed in BedReader(bedisofile, bedClass=FlairBed):
        # ignoring fusion transcripts for now
        if bed.transcript_class != 'fusion':
            isoforms[bed.name] = bed
            if bed.gene_id not in gene_to_isoforms:
                gene_to_isoforms[bed.gene_id] = []
                gene_to_all_exons[bed.gene_id] = set()
                gene_to_chrom[bed.gene_id] = bed.chrom
            gene_to_isoforms[bed.gene_id].append(bed.name)
            for exon in bed.blocks:
                gene_to_all_exons[bed.gene_id].add(exon)
    return isoforms, gene_to_isoforms, gene_to_all_exons, gene_to_chrom

def load_read_maps(read_map_files):
    read_to_isoform = {}
    for label, mapfile in read_map_files:
        for line in open(mapfile):
            iso, reads = line.rstrip().split('\t', 2)
            for read in reads.split(','):
                read_to_isoform[(label, read)] = iso
    return read_to_isoform

def load_bam_file_for_region(bam, bam_label, gene_id, rchrom, rstart, rend, my_vars, genome, readvarinfo_to_reads, read_to_isoform, isoforms):
    with pysam.AlignmentFile(bam, 'rb') as bam:
        for a in bam.fetch(rchrom, rstart, rend):
            if a.is_mapped and not a.is_secondary and not a.is_supplementary:
                if (bam_label, a.query_name) in read_to_isoform:
                    read_iso_id = read_to_isoform[(bam_label, a.query_name)]
                    read_gene_id = isoforms[read_iso_id].gene_id
                    if read_gene_id == gene_id:
                        introns, insertions, deletions = vp.parse_cigar_for_introns_indels(a.cigartuples, a.reference_start)
                        read_id, read_vars = vp.load_bam_read_vars(a, bam_label, deepcopy(my_vars), genome, insertions, deletions)
                        if read_vars is not None:
                            if read_vars not in readvarinfo_to_reads:
                                readvarinfo_to_reads[read_vars] = set()
                            readvarinfo_to_reads[read_vars].add(read_id)

def load_bam_files_for_region(bam, norm_bam, gene_id, gene_chrom, gene_start, gene_end, my_vars, genome, read_to_isoform, isoforms):
    readvarinfo_to_reads = {}
    load_bam_file_for_region(bam, 't', gene_id, gene_chrom, gene_start, gene_end, my_vars, genome, readvarinfo_to_reads, read_to_isoform, isoforms)
    if norm_bam is not None:
        load_bam_file_for_region(norm_bam, 'n', gene_id, gene_chrom, gene_start, gene_end, my_vars, genome, readvarinfo_to_reads, read_to_isoform, isoforms)
    return readvarinfo_to_reads

def group_alleles_by_iso(file_to_read_to_allele_group, read_to_isoform, index_to_allele_group_info):
    # Isoform + allele group to reads
    isoform_to_allele_group_to_reads = {}
    gene_to_tot_reads_from_allele_groups = {}
    for label in file_to_read_to_allele_group:
        for read in file_to_read_to_allele_group[label]:
            iso_id = read_to_isoform[(label, read)]
            allele_group = file_to_read_to_allele_group[label][read]
            file_to_read_to_allele_group[label][read] = iso_id + '|' + allele_group
            gene_id = index_to_allele_group_info[allele_group]['gene']
            if gene_id not in gene_to_tot_reads_from_allele_groups:
                gene_to_tot_reads_from_allele_groups[gene_id] = {'t': 0, 'n': 0}
            if iso_id not in isoform_to_allele_group_to_reads:
                isoform_to_allele_group_to_reads[iso_id] = {}
            if allele_group not in isoform_to_allele_group_to_reads[iso_id]:
                isoform_to_allele_group_to_reads[iso_id][allele_group] = {'t': set(), 'n': set()}
            gene_to_tot_reads_from_allele_groups[gene_id][label] += 1
            isoform_to_allele_group_to_reads[iso_id][allele_group][label].add(read)
    return isoform_to_allele_group_to_reads, gene_to_tot_reads_from_allele_groups

def get_no_var_iso_info(isoform_to_allele_group_to_reads, read_to_isoform):
    # for isoforms/genes with no variants, cannot be allelotyped
    no_var_isoforms_to_reads = {}
    for (label, read), isoform in read_to_isoform.items():
        if isoform not in isoform_to_allele_group_to_reads:
            if isoform not in no_var_isoforms_to_reads:
                no_var_isoforms_to_reads[isoform] = {'t': set(), 'n': set()}
            no_var_isoforms_to_reads[isoform][label].add(read)
    return no_var_isoforms_to_reads

